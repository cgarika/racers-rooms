/* Writes the app's copy of tracks.json: Source/GameNest/Private/Games/Racers/RacersTracks.inl (node tools/gen_inl.js <worktree>). */
"use strict";
const fs = require("fs"), path = require("path");
const wt = process.argv[2];
if (!wt) { console.error("usage: node tools/gen_inl.js <worktree>"); process.exit(2); }
const data = require("../tracks.json");
let out = "/* Generated by racers-rooms/tools/gen_inl.js from tracks.json: the tracks' centreline points, the same ones the server steps cars on. Do not edit. */\n";
out += `constexpr double GTrackHalfW = ${data.halfW};\n`;
let i = 0;
for (const [name, t] of Object.entries(data.tracks)) {
  out += `static const double GTrack_${name}[] = {`;
  out += t.pts.map((p, k) => (k % 8 === 0 ? "\n" : "") + p[0] + "," + p[1]).join(", ");
  out += `};\n`;
  i++;
}
out += "static const struct { const TCHAR* Name; const double* Pts; int32 Count; double BridgeA, BridgeB; } GTrackTable[] = {\n";
for (const [name, t] of Object.entries(data.tracks)) out += `\t{ TEXT("${name}"), GTrack_${name}, ${t.pts.length}, ${t.bridge ? t.bridge[0] : 0}, ${t.bridge ? t.bridge[1] : 0} },\n`;
out += "};\n";
const dest = path.join(wt, "Source/GameNest/Private/Games/Racers");
fs.mkdirSync(dest, { recursive: true });
fs.writeFileSync(path.join(dest, "RacersTracks.inl"), out);
console.log("wrote", path.join(dest, "RacersTracks.inl"));
