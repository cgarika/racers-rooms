/* Writes the app's copy of tracks.json: Source/GameNest/Private/Games/Racers/RacersTracks.inl (node tools/gen_inl.js <worktree>).
   Both geometries: the first tracks (rows 0-2, geometry 1, GTrackHalfW) and the wide ones (rows 3-5, geometry 2, GTrackHalfW2; qa1126). */
"use strict";
const fs = require("fs"), path = require("path");
const wt = process.argv[2];
if (!wt) { console.error("usage: node tools/gen_inl.js <worktree>"); process.exit(2); }
const data = require("../tracks.json");
let out = "/* Generated by racers-rooms/tools/gen_inl.js from tracks.json: the tracks' centreline points, the same ones the server steps cars on. Do not edit. */\n";
out += `constexpr double GTrackHalfW = ${data.halfW};\n`;
out += `constexpr double GTrackHalfW2 = ${data.halfW2};\n`;
const sets = [["", data.tracks, 1], ["2", data.tracks2, 2]];
for (const [suffix, tracks] of sets) for (const [name, t] of Object.entries(tracks)) {
  out += `static const double GTrack${suffix}_${name}[] = {`;
  out += t.pts.map((p, k) => (k % 8 === 0 ? "\n" : "") + p[0] + "," + p[1]).join(", ");
  out += `};\n`;
}
out += "static const struct { const TCHAR* Name; const double* Pts; int32 Count; double BridgeA, BridgeB; int32 Geo; } GTrackTable[] = {\n";
for (const [suffix, tracks, geo] of sets) for (const [name, t] of Object.entries(tracks)) out += `\t{ TEXT("${name}"), GTrack${suffix}_${name}, ${t.pts.length}, ${t.bridge ? t.bridge[0] : 0}, ${t.bridge ? t.bridge[1] : 0}, ${geo} },\n`;
out += "};\n";
const dest = path.join(wt, "Source/GameNest/Private/Games/Racers");
fs.mkdirSync(dest, { recursive: true });
fs.writeFileSync(path.join(dest, "RacersTracks.inl"), out);
console.log("wrote", path.join(dest, "RacersTracks.inl"));
